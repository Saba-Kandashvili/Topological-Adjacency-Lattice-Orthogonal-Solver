#include "cgsme_ruleset.h"
#include <stdio.h>
#include <inttypes.h>

int main(int argc, char **argv)
{
    const char *json_path = (argc > 1) ? argv[1] : "tileset.json";
    const char *out_path  = (argc > 2) ? argv[2] : "cgsme_tileset_baked.h";

    CgsmeRuleset r;
    if (!cgsme_ruleset_load_from_file(json_path, &r))
    {
        fprintf(stderr, "ERROR: Failed to load ruleset from '%s'\n", json_path);
        return 1;
    }

    FILE *f = fopen(out_path, "w");
    if (!f)
    {
        fprintf(stderr, "ERROR: Failed to open output header '%s'\n", out_path);
        return 1;
    }

    fprintf(f, "// AUTO-GENERATED BY cgsme_codegen FROM %s — DO NOT EDIT MANUALLY\n", json_path);
    fprintf(f, "#ifndef CGSME_TILESET_BAKED_H\n#define CGSME_TILESET_BAKED_H\n\n");
    fprintf(f, "#include <stdint.h>\n#include <stdbool.h>\n\n");

    // dynamic integer container
    fprintf(f, "typedef uint%u_t cgsme_tile_t;\n\n", r.container_bits);
    fprintf(f, "#define CGSME_CONTAINER_BITS  %u\n", r.container_bits);
    fprintf(f, "#define CGSME_NUM_TILES       %u\n", r.num_tiles);
    fprintf(f, "#define CGSME_NUM_CATEGORIES  %u\n", r.num_categories);
    fprintf(f, "#define CGSME_NUM_ANCHORS     %u\n", r.num_anchors);
    fprintf(f, "#define CGSME_TILE_INDEX_BITS %u\n", r.tile_index_bits);
    fprintf(f, "#define CGSME_TILE_INDEX_MASK ((cgsme_tile_t)((1ULL << %u) - 1ULL))\n", r.tile_index_bits);
    fprintf(f, "#define CGSME_VISITED_BIT     ((cgsme_tile_t)(1ULL << %u))\n", r.tile_index_bits);
    fprintf(f, "#define CGSME_PACKED_VOID     ((cgsme_tile_t)-1)\n\n");

    // typesafe hardware bit intrinsics
    if (r.container_bits == 64)
    {
        fprintf(f, "#define CGSME_POPCOUNT(x) __builtin_popcountll((uint64_t)(x))\n");
        fprintf(f, "#define CGSME_CTZ(x)      __builtin_ctzll((uint64_t)(x))\n");
    }
    else
    {
        fprintf(f, "#define CGSME_POPCOUNT(x) __builtin_popcount((uint32_t)(x))\n");
        fprintf(f, "#define CGSME_CTZ(x)      __builtin_ctz((uint32_t)(x))\n");
    }
    fprintf(f, "#define CGSME_BIT(i)          (((cgsme_tile_t)1) << (i))\n");
    fprintf(f, "#define Empty_Tile            ((cgsme_tile_t)0)\n");
    fprintf(f, "#define All_Possible_State    ((cgsme_tile_t)0x%" PRIX64 "ULL)\n\n", r.all_possible);

    // individual tile macros and seed/anchor config
    for (int t = 0; t < r.num_tiles; t++)
        fprintf(f, "#define %-24s CGSME_BIT(%d)\n", r.tiles[t].name, t);
    fprintf(f, "\n#define CGSME_SEED_TILE_ID    %u\n", r.seed_tile_id);
    fprintf(f, "#define CGSME_SEED_TILE_MASK  CGSME_BIT(%u)\n", r.seed_tile_id);
    fprintf(f, "#define CGSME_GAUSS_WIDTH     %.4ff\n", r.gauss_width);
    fprintf(f, "#define CGSME_CONNECTOR_BOOST %.4ff\n\n", r.connector_boost);

    // self opening masks (0=N, 1=E, 2=S, 3=W)
    fprintf(f, "static const cgsme_tile_t CGSME_HAS_PORT_MASK[4] = {\n    ");
    for (int d = 0; d < 4; d++)
        fprintf(f, "(cgsme_tile_t)0x%" PRIX64 "ULL%s", r.has_port_mask[d], (d < 3) ? ", " : "\n};\n\n");

    // neighbor propagation LUT [N_TILES + 1][4]
    fprintf(f, "static const cgsme_tile_t CGSME_PROP_MASK[%u][4] = {\n", r.num_tiles + 1);
    for (int t = 0; t <= r.num_tiles; t++)
    {
        fprintf(f, "    { (cgsme_tile_t)0x%" PRIX64 "ULL, (cgsme_tile_t)0x%" PRIX64 "ULL, (cgsme_tile_t)0x%" PRIX64 "ULL, (cgsme_tile_t)0x%" PRIX64 "ULL }%s // %s\n",
                r.prop_mask[t][0], r.prop_mask[t][1], r.prop_mask[t][2], r.prop_mask[t][3],
                (t < r.num_tiles) ? "," : "", (t < r.num_tiles) ? r.tiles[t].name : "Empty_Tile");
    }
    fprintf(f, "};\n\n");

    // open and close transition LUTs [N_TILES][4]
    fprintf(f, "static const uint8_t CGSME_OPEN_LUT[%u][4] = {\n", r.num_tiles);
    for (int t = 0; t < r.num_tiles; t++)
        fprintf(f, "    { %2u, %2u, %2u, %2u }%s // %s\n",
                r.open_lut[t][0], r.open_lut[t][1], r.open_lut[t][2], r.open_lut[t][3],
                (t + 1 < r.num_tiles) ? "," : "", r.tiles[t].name);
    fprintf(f, "};\n\n");

    fprintf(f, "static const uint8_t CGSME_CLOSE_LUT[%u][4] = {\n", r.num_tiles);
    for (int t = 0; t < r.num_tiles; t++)
        fprintf(f, "    { %3u, %3u, %3u, %3u }%s // %s\n",
                r.close_lut[t][0], r.close_lut[t][1], r.close_lut[t][2], r.close_lut[t][3],
                (t + 1 < r.num_tiles) ? "," : "", r.tiles[t].name);
    fprintf(f, "};\n\n");

    // category tables
    fprintf(f, "static const uint8_t CGSME_BIT_TO_CATEGORY[%u] = { ", r.num_tiles);
    for (int t = 0; t < r.num_tiles; t++)
        fprintf(f, "%u%s", r.tiles[t].category_idx, (t + 1 < r.num_tiles) ? ", " : " };\n");

    fprintf(f, "static const float CGSME_CATEGORY_CURVE_POS[%u] = { ", r.num_categories);
    for (int c = 0; c < r.num_categories; c++)
        fprintf(f, "%.2ff%s", r.categories[c].curve_pos, (c + 1 < r.num_categories) ? ", " : " };\n");

    fprintf(f, "static const float CGSME_CATEGORY_MASK_WEIGHT[%u] = { ", r.num_categories);
    for (int c = 0; c < r.num_categories; c++)
        fprintf(f, "%.3ff%s", r.categories[c].mask_weight, (c + 1 < r.num_categories) ? ", " : " };\n");

    fprintf(f, "static const bool CGSME_CATEGORY_BOOST[%u] = { ", r.num_categories);
    for (int c = 0; c < r.num_categories; c++)
        fprintf(f, "%s%s", r.categories[c].connector_boost ? "true" : "false", (c + 1 < r.num_categories) ? ", " : " };\n");

    fprintf(f, "static const bool CGSME_CATEGORY_NATURAL[%u] = { ", r.num_categories);
    for (int c = 0; c < r.num_categories; c++)
        fprintf(f, "%s%s", r.categories[c].natural_spawn ? "true" : "false", (c + 1 < r.num_categories) ? ", " : " };\n\n");

    fprintf(f, "#endif // CGSME_TILESET_BAKED_H\n");
    fclose(f);
    printf("[cgsme_codegen] Generated %s (%u tiles -> uint%u_t)\n", out_path, r.num_tiles, r.container_bits);
    return 0;
}